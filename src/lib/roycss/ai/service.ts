/**
 * Response formatter utilities
 */
export class ResponseFormatter {
  /**
   * Format CSS code block with syntax highlighting wrapper
   */
  static formatCSSCode(css: string): string {
    return `\`\`\`css\n${css.trim()}\n\`\`\``;
  }

  /**
   * Format explanation with markdown
   */
  static formatExplanation(explanation: string, tips?: string[]): string {
    let output = `## Explanation\n\n${explanation}`;
    
    if (tips && tips.length > 0) {
      output += '\n\n### Tips\n';
      tips.forEach((tip, i) => {
        output += `\n${i + 1}. ${tip}`;
      });
    }
    
    return output;
  }

  /**
   * Format complete response with metadata
   */
  static formatResponse(content: string, type: 'css' | 'explanation' | 'general'): string {
    const timestamp = new Date().toLocaleTimeString();
    
    switch (type) {
      case 'css':
        return `${content}\n\n---\n*Generated by RoyAI at ${timestamp}*`;
      
      case 'explanation':
        return `${content}\n\n---\n*Explained by RoyAI at ${timestamp}*`;
      
      default:
        return content;
    }
  }

  /**
   * Extract code blocks from response
   */
  static extractCodeBlocks(text: string): string[] {
    const regex = /```(?:css|scss|less|html)?\n([\s\S]*?)```/g;
    const codes: string[] = [];
    let match;
    
    while ((match = regex.exec(text)) !== null) {
      codes.push(match[1].trim());
    }
    
    return codes;
  }

  /**
   * Validate generated CSS
   */
  static validateCSS(css: string): { valid: boolean; errors: string[] } {
    const errors: string[] = [];
    
    // Check balanced braces
    const openBraces = (css.match(/{/g) || []).length;
    const closeBraces = (css.match(/}/g) || []).length;
    
    if (openBraces !== closeBraces) {
      errors.push(`Unbalanced braces: ${openBraces} opening, ${closeBraces} closing`);
    }
    
    // Check basic structure
    if (!css.includes('{') && !css.includes('}')) {
      errors.push('No valid CSS rule blocks found');
    }
    
    // Check for common issues
    if (/[^{]};\s*{/g.test(css)) {
      errors.push('Possible missing selector before declaration block');
    }
    
    return {
      valid: errors.length === 0,
      errors
    };
  }
}

