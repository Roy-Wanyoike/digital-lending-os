/**
 * Mock AI Service for development/demo
 */
export class MockAIService {
  private config: AIServiceConfig;

  constructor(config: Partial<AIServiceConfig> = {}) {
    this.config = { ...DEFAULT_CONFIG, ...config };
  }

  /**
   * Generate mock response based on input
   */
  private getMockResponse(input: string): () => Promise<string> {
    const lowerInput = input.toLowerCase();
    
    // Pattern matching for responses
    if (lowerInput.includes('bounce') || lowerInput.includes('jump')) {
      return MOCK_RESPONSES['bounce'];
    }
    if (lowerInput.includes('fade') || lowerInput.includes('opacity')) {
      return MOCK_RESPONSES['fade'];
    }
    if (lowerInput.includes('button') || lowerInput.includes('btn')) {
      return MOCK_RESPONSES['button'];
    }
    if (lowerInput.includes('gradient')) {
      return MOCK_RESPONSES['gradient'];
    }
    if (lowerInput.includes('card')) {
      return MOCK_RESPONSES['card'];
    }
    
    return MOCK_RESPONSES['default'];
  }

  /**
   * Process request and generate response
   */
  async processRequest(request: AIRequest): Promise<AIMessage> {
    const mockResponseFn = this.getMockResponse(request.prompt);
    const content = await mockResponseFn();

    return {
      role: 'assistant',
      content,
      timestamp: new Date()
    };
  }

  /**
   * Generate CSS effect
   */
  async generateEffect(description: string): Promise<AIGeneratedEffect> {
    const response = await this.processRequest({
      prompt: description,
      context: 'effect'
    });

    const cssCode = ResponseFormatter.extractCodeBlocks(response.content)[0] || '';

    return {
      name: this.generateName(description),
      css: cssCode,
      explanation: response.content.split('```')[2]?.trim() || 'Generated CSS effect',
      tailwind: this.convertToTailwindHint(cssCode)
    };
  }

  /**
   * Stream response for real-time display
   */
  async *streamResponse(input: string): AsyncGenerator<string> {
    const response = await this.processRequest({ prompt: input });
    const words = response.content.split(' ');
    
    for (let i = 0; i < words.length; i++) {
      yield words[i] + (i < words.length - 1 ? ' ' : '');
      await new Promise(r => setTimeout(r, 30));
    }
  }

  /**
   * Generate a class name from description
   */
  private generateName(description: string): string {
    return description
      .toLowerCase()
      .replace(/[^a-z0-9\s]/g, '')
      .split(' ')
      .slice(0, 3)
      .join('-')
      || 'generated-effect';
  }

  /**
   * Simple Tailwind conversion hint
   */
  private convertToTailwindHint(css: string): string | undefined {
    const hints: string[] = [];
    
    if (css.includes('flex')) hints.push('flex');
    if (css.includes('hidden') || css.includes('opacity: 0')) hints.push('opacity-0');
    if (css.includes('rounded')) hints.push('rounded-lg');
    if (css.includes('transition')) hints.push('transition-all');
    if (css.includes('hover')) hints.push('hover:*');
    
    return hints.length > 0 ? `class="${hints.join(' ')}"` : undefined;
  }
}

/**
 * Main AI Service class
 * Provides unified interface for AI operations
 */
export class RoyAIService {
  private config: AIServiceConfig;
  private mockService: MockAIService;

  constructor(config: Partial<AIServiceConfig> = {}) {
    this.config = { ...DEFAULT_CONFIG, ...config };
    this.mockService = new MockAIService(this.config);
  }

  /**
   * Get current configuration
   */
  getConfig(): Readonly<AIServiceConfig> {
    return { ...this.config };
  }

  /**
   * Update configuration
   */
  updateConfig(updates: Partial<AIServiceConfig>): void {
    this.config = { ...this.config, ...updates };
    this.mockService = new MockAIService(this.config);
  }

  /**
   * Process chat message
   */
  async chat(message: string, context?: AIRequest['context']): Promise<AIMessage> {
    return this.mockService.processRequest({ prompt: message, context });
  }

  /**
   * Generate CSS effect
   */
  async generateEffect(description: string): Promise<AIGeneratedEffect> {
    return this.mockService.generateEffect(description);
  }

  /**
   * Stream chat response
   */
  async *streamChat(message: string): AsyncGenerator<string> {
    yield* this.mockService.streamResponse(message);
  }

  /**
   * Explain CSS code
   */
  async explainCSS(code: string): Promise<CSSExplanation> {
    // Mock explanation
    return {
      summary: 'This CSS creates visual styling effects.',
      properties: [
        {
          property: 'animation',
          value: code.match(/animation:\s*([^;]+)/)?.[1] || 'defined',
          explanation: 'Controls the animation behavior',
          browserSupport: 'Modern browsers',
          alternatives: ['transition']
        }
      ],
      tips: [
        'Consider using will-change for better performance',
        'Test animations with prefers-reduced-motion'
      ]
    };
  }

  /**
   * Convert CSS to Tailwind classes
   */
  async cssToTailwind(css: string): Promise<TailwindClasses> {
    const classes: string[] = [];
    
    // Simple conversions
    if (/display:\s*flex/.test(css)) classes.push('flex');
    if (/justify-content:\s*center/.test(css)) classes.push('justify-center');
    if (/align-items:\s*center/.test(css)) classes.push('items-center');
    if (/padding:\s*(\d+)px/.test(css)) {
      const match = css.match(/padding:\s*(\d+)px/);
      classes.push(`p-[${match?.[1]}px]`);
    }
    if (/border-radius/.test(css)) classes.push('rounded-lg');
    if (/transition/.test(css)) classes.push('transition-all');

    return {
      classes: classes.join(' ') || '/* Manual conversion needed */',
      notes: classes.length > 0 
        ? ['Some properties may need custom values'] 
        : ['Complex CSS requires manual conversion'],
      htmlExample: `<div class="${classes.join(' ')}">...</div>`
    };
  }

  /**
   * Check if service is ready
   */
  isReady(): boolean {
    return true; // Mock service is always ready
  }

  /**
   * Get service status
   */
  getStatus(): { provider: string; ready: boolean; latency: number } {
    return {
      provider: this.config.provider,
      ready: this.isReady(),
      latency: Math.random() * 100 + 50 // Simulated latency
    };
  }
}

// Singleton instance
let serviceInstance: RoyAIService | null = null;

/**
 * Get or create AI service instance
 */
export function getRoyAIService(config?: Partial<AIServiceConfig>): RoyAIService {
  if (!serviceInstance) {
    serviceInstance = new RoyAIService(config);
  } else if (config) {
    serviceInstance.updateConfig(config);
  }
  
  return serviceInstance;
}

/**
 * Reset service instance (for testing)
 */
export function resetRoyAIService(): void {
  serviceInstance = null;
}

// Re-exports
export { MockAIService, ResponseFormatter };
export default RoyAIService;
