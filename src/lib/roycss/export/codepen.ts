/**
 * Get export format based on target
 */
export function getExporter(format: ExportOptions['format']) {
  switch (format) {
    case 'codepen':
      return exportToCodePen;
    case 'codesandbox':
      return exportToCodeSandbox;
    case 'github-gist':
      return exportToGitHubGist;
    default:
      throw new Error(`Unsupported export format: ${format}`);
  }
}

/**
 * Quick export helper - auto-detect best method or download
 */
export async function quickExport(
  data: ComponentExportData,
  options: ExportOptions
): Promise<ExportResult> {
  if (typeof window !== 'undefined' && navigator.clipboard) {
    // Try clipboard first for easy sharing
    const html = generateStandaloneHTML(data, options);
    await navigator.clipboard.writeText(html);
    
    return {
      success: true,
      payload: { message: 'Copied to clipboard!' },
    };
  }

  // Fallback to download
  downloadAsHTML(data, options);
  return {
    success: true,
    payload: { message: 'Downloaded as HTML file' },
  };
}
