/**
 * Generate shareable URL with encoded component data
 */
export function generateShareURL(
  data: ComponentExportData,
  options: ExportOptions
): string {
  const payload = JSON.stringify({
    ...data,
    title: options.title,
    description: options.description,
  });

  // Encode for URL (in production, you'd use a proper shortening service)
  const encoded = btoa(payload);
  
  // Return a placeholder URL pattern
  return `https://roycss.dev/share?c=${encoded.slice(0, 100)}...`; // Truncated for demo
}

