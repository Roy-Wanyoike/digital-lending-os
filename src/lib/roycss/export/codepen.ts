// HTML File Export
// ============================================================================

/**
 * Generate standalone HTML file
 */
export function generateStandaloneHTML(
  data: ComponentExportData,
  options: ExportOptions
): string {
  const externalStyles = (options.externalStyles || [])
    .map((s) => `<link rel="stylesheet" href="${s}" />`)
    .join('\n');

  const externalScripts = (options.externalScripts || [])
    .map((s) => `<script src="${s}"></script>`)
    .join('\n');

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${options.title}</title>
  <meta name="description" content="${options.description}">
  ${externalStyles}
  <style>
/* ROYCSS Component Styles */
${data.css}
  </style>
</head>
<body>
  <!-- ${options.title} - Generated by ROYCSS -->
  ${data.html}

  ${externalScripts}
  <script>
// ROYCSS Component Script
${data.js}
  </script>
</body>
</html>`;
}

/**
 * Download as HTML file
 */
export function downloadAsHTML(
  data: ComponentExportData,
  options: ExportOptions
): void {
  const html = generateStandaloneHTML(data, options);
  const blob = new Blob([html], { type: 'text/html' });
  const url = URL.createObjectURL(blob);

  const link = document.createElement('a');
  link.href = url;
  link.download = `${options.title.toLowerCase().replace(/\s+/g, '-')}.html`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

