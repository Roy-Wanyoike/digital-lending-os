/**
 * ROYCSS Export System - CodePen & External Platform Exports
 * @module roycss/export
 * @description Utilities for exporting components to external platforms like CodePen, CodeSandbox, etc.
 */

import type { ExportOptions, ExportResult } from '../types';

// ============================================================================
// Types
// ============================================================================

export interface ComponentExportData {
  /** Component name */
  name: string;
  /** HTML content */
  html: string;
  /** CSS content */
  css: string;
  /** JavaScript content */
  js: string;
  /** Dependencies (for npm packages) */
  dependencies?: Record<string, string>;
}

// ============================================================================
// CodePen Export
// ============================================================================

const CODEPEN_API_URL = 'https://codepen.io/pen/define';

/**
 * Generate CodePen payload from component data
 */
function generateCodePenPayload(
  data: ComponentExportData,
  options: ExportOptions
): Record<string, unknown> {
  const payload = {
    title: options.title,
    description: options.description,
    html: wrapHTML(data.html),
    css: wrapCSS(data.css),
    js: wrapJS(data.js),
    css_external: options.externalStyles?.join(';') || undefined,
    js_external: options.externalScripts?.join(';') || undefined,
    editors: '101', // Show all editors by default
    layout: 'left', // Editor layout
  };

  return payload;
}

/**
 * Wrap HTML with boilerplate
 */
function wrapHTML(html: string): string {
  return `<!-- Generated by ROYCSS Component System -->
<div class="roycss-demo">
  ${html}
</div>`;
}

/**
 * Wrap CSS with base styles
 */
function wrapCSS(css: string): string {
  return `/* Generated by ROYCSS Component System */
/* Base Styles */
* {
  box-sizing: border-box;
  margin: 0;
  padding: 0;
}

body {
  font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, Oxygen, Ubuntu, sans-serif;
  line-height: 1.6;
  color: #111827;
  background-color: #ffffff;
  padding: 2rem;
}

.roycss-demo {
  max-width: 800px;
  margin: 0 auto;
}

/* Component Styles */
${css}`;
}

/**
 * Wrap JS with boilerplate
 */
function wrapJS(js: string): string {
  return `// Generated by ROYCSS Component System
document.addEventListener('DOMContentLoaded', function() {
  ${js}
});`;
}

/**
 * Export component to CodePen
 * Opens a new window/tab with the CodePen editor pre-filled with the component code.
 */
export async function exportToCodePen(
  data: ComponentExportData,
  options: ExportOptions
): Promise<ExportResult> {
  try {
    const payload = generateCodePenPayload(data, options);
    
    // Create form and submit to open in new window
    const form = document.createElement('form');
    form.method = 'POST';
    form.action = CODEPEN_API_URL;
    form.target = '_blank';

    const input = document.createElement('input');
    input.type = 'hidden';
    input.name = 'data';
    input.value = JSON.stringify(payload);

    form.appendChild(input);
    document.body.appendChild(form);
    form.submit();
    document.body.removeChild(form);

    return {
      success: true,
      url: `${CODEPEN_API_URL}?${encodeURIComponent(JSON.stringify(payload))}`,
      payload,
    };
  } catch (error) {
    return {
      success: false,
      error: error instanceof Error ? error.message : 'Failed to export to CodePen',
    };
  }
}

/**
 * Generate CodePen embed URL for embedding the pen
 */
export function generateCodePenEmbedUrl(penId: string, options?: {
  height?: number;
  theme?: 'light' | 'dark' | 'default';
  editable?: boolean;
}): string {
  const height = options?.height || 400;
  const theme = options?.theme || 'default';
  const editable = options?.editable ? 'true' : 'false';

  return `https://codepen.io/embed/preview/${penId}?height=${height}&theme-id=${theme}&editable=${editable}`;
}

